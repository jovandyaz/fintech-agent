import {
  CARD_TYPES,
  type Customer,
  type Transaction,
} from '@fintech-agent/contracts';

import { DATASET_NOW } from './scenarios.js';

const BANK_TIME_ZONE = 'America/Mexico_City';
const LOCAL_DATE = new Intl.DateTimeFormat('en-CA', {
  timeZone: BANK_TIME_ZONE,
  year: 'numeric',
  month: '2-digit',
  day: '2-digit',
});
const LOCAL_TIME = new Intl.DateTimeFormat('en-GB', {
  timeZone: BANK_TIME_ZONE,
  hour: '2-digit',
  minute: '2-digit',
  hourCycle: 'h23',
});
const AMOUNT = new Intl.NumberFormat('en-US', {
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
});

const localTime = (iso: string): string => {
  const at = new Date(iso);
  return `${LOCAL_DATE.format(at)} ${LOCAL_TIME.format(at)}`;
};

const partyOf = (tx: Transaction): string =>
  tx.type === CARD_TYPES[0] ? tx.merchant_descriptor : tx.counterparty_name;

const rowOf = (tx: Transaction): string =>
  `| ${localTime(tx.created_at)} | ${tx.id} | ${tx.type} | ${tx.status} | $${AMOUNT.format(tx.amount)} | ${partyOf(tx)} |`;

/**
 * The dataset as a reviewer reads it to write a new case: each customer with
 * their movements, newest first, and never a CLABE, card number, RFC, CURP,
 * phone or email.
 */
export function customersMarkdown(
  customers: readonly Customer[],
  transactions: readonly Transaction[],
): string {
  const sections = customers.map((customer) => {
    const own = transactions
      .filter((tx) => tx.customer_id === customer.id)
      .sort((a, b) => Date.parse(b.created_at) - Date.parse(a.created_at));
    return [
      `## ${customer.id} · ${customer.first_name} ${customer.last_names}`,
      '',
      `Account ${customer.account_status}, KYC ${customer.kyc_level}, card ${customer.card_status}. ${own.length} movements.`,
      '',
      '| Created (Mexico City) | Id | Type | Status | Amount (MXN) | Counterparty or merchant |',
      '| --- | --- | --- | --- | --- | --- |',
      ...own.map(rowOf),
    ].join('\n');
  });
  return [
    '# Customers and movements',
    '',
    `Synthetic data, generated by \`pnpm --filter @fintech-agent/data generate\`; do not edit by hand. The data is frozen at ${localTime(DATASET_NOW)} (Mexico City), and the local stack receives live cases on that clock (\`CASE_CLOCK=dataset\`, README), so "ayer" in a new case means the day before. To try a case of your own, pick a customer below in the console's **Nuevo caso** and describe one of their movements in your own words.`,
    '',
    ...sections.flatMap((section) => [section, '']),
  ].join('\n');
}
